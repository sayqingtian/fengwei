const digest = value => createHash('sha256').update(value).digest('hex');
const image = size => joinPhoto({ type: 'image/avif', bytes: new Uint8Array(size).fill(71) });
async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), 'fengwei-photos-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const store = new FileStore(root);
  return { store, photos: new Photos(store) };
}
test('binary photo packet round trips UTF-8 metadata and bytes, and rejects truncated or excess payloads', () => {
  const pictures = [splitPhoto(image(80000)), { type: 'image/webp', bytes: new Uint8Array([0, 255, 128, 63]) }];
  const metadata = { title: '妈妈的菜谱', hashes: ['first', 'second'] };
  const packed = packPhotos(metadata, pictures);
  assert.deepEqual(unpackPhotos(packed), { metadata, photos: pictures });
  assert.ok(packed.length < 80500);
  assert.throws(() => unpackPhotos(packed.slice(0, -1)));
  assert.throws(() => unpackPhotos(new Uint8Array([...packed, 0])));
  const invalid = packed.slice(); invalid[0] = 0;
  assert.throws(() => unpackPhotos(invalid));
  assert.throws(() => unpackPhotos(packPhotos({}, [{ type: 'text/html', bytes: new Uint8Array([1]) }])));
  assert.throws(() => unpackPhotos(packPhotos({}, Array(9).fill(pictures[1]))));
});
test('photos use binary storage, deduplicate and survive new store instances', async t => {
  const { store, photos } = await fixture(t), photo = image(80000);
  const hash = await photos.save(photo);
  assert.equal(await photos.save(photo), hash);
  assert.equal(await store.get(`photos/${hash}.txt`), null);
  assert.equal((await store.get(`photos/${hash}.bin`, { type: 'arrayBuffer' })).byteLength, 80001);
  assert.equal(joinPhoto(await new Photos(new FileStore(store.root)).get(hash)), photo);
  assert.equal((await store.list({ prefix: 'photos/' })).blobs.length, 1);
});
test('legacy and historical references resolve after optimization, with durable receipts and retry-safe cleanup', async t => {
  const { store, photos } = await fixture(t), legacy = image(1000), hash = digest(legacy), smaller = image(100);
  await store.set(`photos/${hash}.txt`, legacy);
  const memoized = requestStore(store), cached = new Photos(memoized);
  assert.equal(await memoized.run(async () => joinPhoto(await cached.get(hash))), legacy);
  let failOnce = true;
  const originalDelete = store.delete.bind(store);
  store.delete = async key => { if (failOnce) { failOnce = false; throw new Error('Injected cleanup interruption'); } return originalDelete(key); };
  await assert.rejects(() => photos.optimize(hash, smaller, { action: 'photo.optimize' }), /interruption/);
  assert.equal(joinPhoto(await photos.get(hash)), smaller, 'alias is valid before source cleanup');
  const result = await photos.optimize(hash, smaller);
  assert.equal(result.changed, false);
  assert.equal(await store.get(`photos/${hash}.txt`), null);
  assert.equal(await memoized.run(async () => joinPhoto(await cached.get(hash))), smaller, 'aliases cannot be hidden by old immutable photo caches');
  assert.ok((await store.get('private/photo-cache-version.json', { type: 'json' })).version);
  const inventory = await photos.inventory();
  assert.equal(inventory.items.length, 1);
  assert.equal(inventory.items[0].optimized, true);
  assert.equal(inventory.items[0].bytes, 101);
});
test('verification failure preserves original bytes and does not publish an alias', async t => {
  const { store, photos } = await fixture(t), legacy = image(1000), hash = digest(legacy);
  await store.set(`photos/${hash}.txt`, legacy);
  const set = store.set.bind(store);
  store.set = async (key, value, options) => set(key, key.endsWith('.bin') ? new Uint8Array([3, 255]) : value, options);
  await assert.rejects(() => photos.optimize(hash, image(100)), /verification/);
  assert.equal(await store.get(`photos/${hash}.txt`), legacy);
  assert.equal(await store.get(`private/photo-optimizations/${hash}.json`), null);
});
test('optimization never enlarges small images and accounts for duplicate legacy objects', async t => {
  const { store, photos } = await fixture(t), original = image(100), hash = digest(original);
  await store.set(`photos/${hash}.txt`, original);
  await photos.save(original);
  const before = (await photos.inventory()).items[0];
  assert.equal(before.bytes, Buffer.byteLength(original) + 101);
  assert.equal(before.optimized, false);
  const result = await photos.optimize(hash, image(200));
  assert.equal(result.targetHash, hash);
  assert.equal(result.savedBytes, Buffer.byteLength(original));
  assert.equal(joinPhoto(await photos.get(hash)), original);
  assert.equal((await photos.inventory()).items[0].bytes, 101);
});
test('optimization reuses an existing target and reports the actual released object bytes', async t => {
  const { store, photos } = await fixture(t), legacy = image(1000), hash = digest(legacy), smaller = image(100);
  await store.set(`photos/${hash}.txt`, legacy);
  await photos.save(smaller);
  const result = await photos.optimize(hash, smaller);
  assert.equal(result.savedBytes, Buffer.byteLength(legacy));
  assert.equal((await photos.inventory()).items.length, 1);
});
test('binary API enforces authorization, account identity, body limits, and preserves recipe history', async t => {
  const { store } = await fixture(t), database = new RecipeDatabase(store), password = 'image-test-password';
  const api = createApi({ database, password });
  async function call(path, method = 'GET', value, cookie, binary = false, accept = false) {
    return api(new Request(`https://recipes.test/api/${path}`, { method, headers: { ...(cookie ? { Cookie: cookie } : {}), ...(value !== undefined ? { 'Content-Type': binary ? PHOTO_PACKET_TYPE : 'application/json', Origin: 'https://recipes.test' } : {}), ...(accept ? { Accept: PHOTO_PACKET_TYPE } : {}) }, ...(value !== undefined ? { body: binary ? value : JSON.stringify(value) } : {}) }));
  }
  const logged = await call('login', 'POST', { username: 'wupanfeng', password }), cookie = logged.headers.get('set-cookie').split(';')[0], owner = (await logged.json()).user;
  const registered = await call('register', 'POST', { displayName: '图片测试只读用户', password, registrationId: randomUUID() }), viewerCookie = registered.headers.get('set-cookie').split(';')[0];
  const photo = 'data:image/png;base64,' + (await readFile(new URL('../dist/icons/icon-192.png', import.meta.url))).toString('base64');
  const recipe = { id: 'photo-test', title: '照片测试', category: '家常菜', description: '', notes: '', minutes: 1, servings: 2, favorite: false, photo: '', ingredients: [], steps: [], createdAt: '2026-10-13T00:00:00Z', updatedAt: '2026-10-13T00:00:00Z' };
  const metadata = { recipe, expectedUserId: owner.id, baseRevision: null, mutationId: randomUUID() };
  const packet = packPhotos(metadata, [splitPhoto(photo)]);
  assert.equal((await call('recipe/photo-test', 'PUT', packet, viewerCookie, true)).status, 403);
  assert.equal((await call('recipe/photo-test', 'PUT', packPhotos({ ...metadata, expectedUserId: 'wrong' }, [splitPhoto(photo)]), cookie, true)).status, 409);
  assert.equal((await call('recipe/photo-test', 'PUT', packPhotos(metadata, [splitPhoto(image(160 * 1024 + 1))]), cookie, true)).status, 413);
  assert.equal((await call('recipe/photo-test', 'PUT', packet.slice(0, -1), cookie, true)).status, 400);
  const saved = await call('recipe/photo-test', 'PUT', packet, cookie, true);
  assert.equal(saved.status, 200); const item = (await saved.json()).item;
  assert.equal((await call('recipe/photo-test', 'PUT', packet, cookie, true)).status, 200);
  assert.equal((await database.history(recipe.id)).length, 1);
  assert.equal((await call(`photo/${item.photoHash}`, 'GET', undefined, undefined, false, true)).status, 401);
  const fetched = await call(`photo/${item.photoHash}`, 'GET', undefined, viewerCookie, false, true);
  assert.equal(fetched.headers.get('content-type'), PHOTO_PACKET_TYPE);
  assert.match(fetched.headers.get('cache-control'), /no-store/);
  assert.equal(joinPhoto(unpackPhotos(await fetched.arrayBuffer()).photos[0]), photo);
  const batch = unpackPhotos(await (await call('photos', 'POST', { hashes: [item.photoHash] }, cookie, false, true)).arrayBuffer());
  assert.deepEqual(batch.metadata.hashes, [item.photoHash]);
  assert.equal((await call('admin/photos', 'GET', undefined, viewerCookie)).status, 403);
  const optimization = packPhotos({ expectedUserId: owner.id }, [splitPhoto(image(100))]);
  assert.equal((await call(`admin/photos/${item.photoHash}`, 'PUT', optimization, viewerCookie, true)).status, 403);
  const originalFetch = globalThis.fetch; t.after(() => { globalThis.fetch = originalFetch; });
  globalThis.fetch = (url, options = {}) => { const target = new URL(url); return api(new Request(`https://recipes.test/api/${target.pathname.split('/api/')[1]}${target.search}`, { ...options, headers: { ...options.headers, Cookie: cookie, Origin: 'https://recipes.test' } })); };
  const local = new Map(), client = await createRemoteStore({ async setting(key) { return local.get(key); }, async setSetting(key, value) { local.set(key, structuredClone(value)); } });
  assert.equal((await client.all())[0].photo, photo);
  const before = (await (await call('recipes', 'GET', undefined, cookie)).json()).capabilities.photoVersion;
  assert.equal((await call(`admin/photos/${item.photoHash}`, 'PUT', optimization, cookie, true)).status, 200);
  const after = (await (await call('recipes', 'GET', undefined, cookie)).json()).capabilities.photoVersion;
  assert.notEqual(before, after);
  assert.equal((await client.all())[0].photo, image(100), 'another device invalidates the old image cache on sync');
  assert.equal([...local.values()][0].recipes[0].photo, image(100), 'offline cache stores the optimized image');
  assert.equal((await database.history(recipe.id))[0].photoHash, item.photoHash);
  assert.equal(await database.photo(item.photoHash), image(100));
  const audit = await (await call('audit', 'GET', undefined, cookie)).json();
  assert.ok(audit.items.some(entry => entry.action === 'photo.optimize' && entry.result === 'success'));
});
